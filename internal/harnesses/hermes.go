package harnesses

import (
	"fmt"
	"os"
	"path/filepath"
)

func detectHermes() (string, bool) {
	dir := filepath.Join(homeDir(), ".hermes")
	if _, err := os.Stat(dir); err == nil {
		return dir, true
	}
	return "", false
}

func applyHermes(vars map[string]string) ([]string, []string) {
	hermesDir := filepath.Join(homeDir(), ".hermes")
	if _, err := os.Stat(hermesDir); os.IsNotExist(err) {
		return nil, nil
	}

	var applied []string
	var warnings []string

	bg := firstHex(vars["background"], "#1e1e2e")
	fg := firstHex(vars["foreground"], "#cdd6f4")
	accent := firstHex(vars["accent"], "#89b4fa")
	surface := firstHex(vars["dark_bg"], "#181825")
	muted := firstHex(vars["bright_black"], "#45475a")

	// 1. Dashboard theme (web UI)
	dashDir := filepath.Join(hermesDir, "dashboard-themes")
	if err := os.MkdirAll(dashDir, 0o755); err != nil {
		warnings = append(warnings, fmt.Sprintf("hermes dashboard dir: %v", err))
		return applied, warnings
	}

	dashYAML := fmt.Sprintf(`# Generated by Aether — safe theme override.
# Original config backed up to .aether.bak.

name: aether
type: dark

palette:
  background: %s
  foreground: %s
  surface: %s
  accent: %s
  muted: %s
  border: %s
  success: %s
  warning: %s
  error: %s

colorOverrides:
  sidebarBg: %s
  sidebarFg: %s
  headerBg: %s
  headerFg: %s
  panelBg: %s
  panelFg: %s
  inputBg: %s
  inputFg: %s
  buttonBg: %s
  buttonFg: %s

customCSS: |
  :root {
    --aether-bg: %s;
    --aether-fg: %s;
    --aether-surface: %s;
    --aether-accent: %s;
    --aether-muted: %s;
    --aether-border: %s;
  }
`, bg, fg, surface, accent, muted, bg, firstHex(vars["base0B"], "#a6e3a1"), firstHex(vars["base0A"], "#f9e2af"), firstHex(vars["base08"], "#f38ba8"),
		surface, fg, surface, fg, surface, fg, bg, fg, accent, fg,
		bg, fg, surface, accent, muted, bg)

	dashPath := filepath.Join(dashDir, "aether.yaml")
	if err := writeFileAtomic(dashPath, []byte(dashYAML)); err != nil {
		warnings = append(warnings, fmt.Sprintf("hermes dashboard theme: %v", err))
	} else {
		applied = append(applied, "hermes-dashboard")
	}

	// 2. Skin (CLI/TUI)
	skinDir := filepath.Join(hermesDir, "skins")
	if err := os.MkdirAll(skinDir, 0o755); err != nil {
		warnings = append(warnings, fmt.Sprintf("hermes skins dir: %v", err))
		return applied, warnings
	}

	skinYAML := fmt.Sprintf(`# Generated by Aether — safe theme override.
name: aether
type: dark

terminal:
  background: %s
  foreground: %s
  cursor: %s
  selectionBg: %s
  selectionFg: %s

border:
  focused: %s
  blurred: %s

text:
  normal: %s
  muted: %s
  accent: %s
  success: %s
  warning: %s
  error: %s
`, bg, fg, accent, firstHex(vars["selection_background"], accent), firstHex(vars["selection_foreground"], bg),
		accent, muted, fg, muted, accent, firstHex(vars["base0B"], "#a6e3a1"), firstHex(vars["base0A"], "#f9e2af"), firstHex(vars["base08"], "#f38ba8"))

	skinPath := filepath.Join(skinDir, "aether.yaml")
	if err := writeFileAtomic(skinPath, []byte(skinYAML)); err != nil {
		warnings = append(warnings, fmt.Sprintf("hermes skin: %v", err))
	} else {
		applied = append(applied, "hermes-skin")
	}

	// 3. Hermes Desktop (Electron tray UI)
	dApplied, dWarnings := applyHermesDesktop(vars)
	applied = append(applied, dApplied...)
	warnings = append(warnings, dWarnings...)

	return applied, warnings
}
