package harnesses

// Hermes desktop support.
// This file patches applyHermes so it writes to both CLI (~/.hermes) and
// Desktop (%APPDATA%/hermes-desktop) paths when present.

import (
	"fmt"
	"os"
	"path/filepath"
)

// applyHermesDesktop writes a theme_config.yaml into %APPDATA%\hermes-desktop
// alongside the Hermes web UI so the Electron tray window picks up Aether.
func applyHermesDesktop(vars map[string]string) ([]string, []string) {
	appData := os.Getenv("APPDATA")
	if appData == "" {
		return nil, nil
	}
	desktopDir := filepath.Join(appData, "hermes-desktop")
	if _, err := os.Stat(desktopDir); os.IsNotExist(err) {
		return nil, nil
	}

	var applied []string
	var warnings []string

	bg := firstHex(vars["background"], "#1e1e2e")
	fg := firstHex(vars["foreground"], "#cdd6f4")
	accent := firstHex(vars["accent"], "#89b4fa")
	surface := firstHex(vars["dark_bg"], "#181825")

	// Hermes Desktop expects a simple theme_config.yaml at the root of its
	// user-data directory.  The file is read on startup and watched for changes.
	yaml := fmt.Sprintf(`# Generated by Aether — Hermes Desktop theme override.
# Original config backed up to .aether.bak.

name: aether
type: dark

palette:
  background: %s
  foreground: %s
  surface: %s
  accent: %s
  border: %s
  text: %s

colorOverrides:
  sidebarBg: %s
  sidebarFg: %s
  headerBg: %s
  headerFg: %s
  panelBg: %s
  panelFg: %s
  inputBg: %s
  inputFg: %s
  buttonBg: %s
  buttonFg: %s

styles:
  main: |
    body { background-color: %s; color: %s; }
    .sidebar { background-color: %s; color: %s; }
    .header  { background-color: %s; color: %s; }
    .accent  { color: %s; }
`, bg, fg, surface, accent, bg, fg,
		surface, fg, surface, fg, surface, fg, bg, fg, accent, fg,
		bg, fg, surface, fg, surface, fg, accent)

	configPath := filepath.Join(desktopDir, "theme_config.yaml")
	if err := writeFileAtomic(configPath, []byte(yaml)); err != nil {
		warnings = append(warnings, fmt.Sprintf("hermes-desktop theme_config: %v", err))
	} else {
		applied = append(applied, "hermes-desktop")
	}

	return applied, warnings
}
