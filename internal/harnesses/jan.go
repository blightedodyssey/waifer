package harnesses

import (
	"fmt"
	"os"
	"path/filepath"
)

func detectJan() (string, bool) {
	// Jan Desktop — check typical locations
	for _, base := range []string{
		filepath.Join(homeDir(), "jan"),
		filepath.Join(os.Getenv("APPDATA"), "Jan"),
		filepath.Join(os.Getenv("LOCALAPPDATA"), "Programs", "jan"),
	} {
		if base == "" {
			continue
		}
		if _, err := os.Stat(base); err == nil {
			return base, true
		}
	}
	return "", false
}

func applyJan(vars map[string]string) ([]string, []string) {
	var applied []string
	var warnings []string

	// Find Jan installation
	var janDir string
	for _, base := range []string{
		filepath.Join(homeDir(), "jan"),
		filepath.Join(os.Getenv("APPDATA"), "Jan"),
		filepath.Join(os.Getenv("LOCALAPPDATA"), "Programs", "jan"),
	} {
		if base == "" {
			continue
		}
		if _, err := os.Stat(base); err == nil {
			janDir = base
			break
		}
	}

	if janDir == "" {
		return applied, warnings
	}

	bg := firstHex(vars["background"], "#1e1e2e")
	fg := firstHex(vars["foreground"], "#cdd6f4")
	accent := firstHex(vars["accent"], "#89b4fa")
	surface := firstHex(vars["dark_bg"], "#181825")
	muted := firstHex(vars["bright_black"], "#45475a")

	themeDir := filepath.Join(janDir, "themes")
	if err := os.MkdirAll(themeDir, 0o755); err != nil {
		warnings = append(warnings, fmt.Sprintf("jan themes dir: %v", err))
		return applied, warnings
	}

	// 1. Write JSON theme variables
	theme := map[string]interface{}{
		"name": "aether",
		"type": "dark",
		"variables": map[string]interface{}{
			"background": bg,
			"foreground": fg,
			"accent":     accent,
			"surface":    surface,
			"muted":      muted,
			"base00":     firstHex(vars["base00"], "#1e1e2e"),
			"base01":     firstHex(vars["base01"], "#181825"),
			"base02":     firstHex(vars["base02"], "#313244"),
			"base03":     firstHex(vars["base03"], "#45475a"),
			"base04":     firstHex(vars["base04"], "#585b70"),
			"base05":     firstHex(vars["base05"], "#cdd6f4"),
			"base06":     firstHex(vars["base06"], "#f5e0dc"),
			"base07":     firstHex(vars["base07"], "#b4befe"),
			"base08":     firstHex(vars["base08"], "#f38ba8"),
			"base09":     firstHex(vars["base09"], "#fab387"),
			"base0A":     firstHex(vars["base0A"], "#f9e2af"),
			"base0B":     firstHex(vars["base0B"], "#a6e3a1"),
			"base0C":     firstHex(vars["base0C"], "#94e2d5"),
			"base0D":     firstHex(vars["base0D"], "#89b4fa"),
			"base0E":     firstHex(vars["base0E"], "#cba6f7"),
			"base0F":     firstHex(vars["base0F"], "#f2cdcd"),
		},
	}

	themeData, _ := jsonMarshal(theme)
	if err := writeFileAtomic(filepath.Join(themeDir, "aether.json"), themeData); err != nil {
		warnings = append(warnings, fmt.Sprintf("jan theme json: %v", err))
	} else {
		applied = append(applied, "jan-theme-json")
	}

	// 2. Write CSS file with CSS custom properties
	cssContent := fmt.Sprintf(`/* Generated by Aether — safe theme file */
:root {
  --bg: %s;
  --fg: %s;
  --accent: %s;
  --surface: %s;
  --muted: %s;
  --base00: %s;
  --base01: %s;
  --base02: %s;
  --base03: %s;
  --base04: %s;
  --base05: %s;
  --base06: %s;
  --base07: %s;
  --base08: %s;
  --base09: %s;
  --base0A: %s;
  --base0B: %s;
  --base0C: %s;
  --base0D: %s;
  --base0E: %s;
  --base0F: %s;
}
`, bg, fg, accent, surface, muted,
		firstHex(vars["base00"], "#1e1e2e"),
		firstHex(vars["base01"], "#181825"),
		firstHex(vars["base02"], "#313244"),
		firstHex(vars["base03"], "#45475a"),
		firstHex(vars["base04"], "#585b70"),
		firstHex(vars["base05"], "#cdd6f4"),
		firstHex(vars["base06"], "#f5e0dc"),
		firstHex(vars["base07"], "#b4befe"),
		firstHex(vars["base08"], "#f38ba8"),
		firstHex(vars["base09"], "#fab387"),
		firstHex(vars["base0A"], "#f9e2af"),
		firstHex(vars["base0B"], "#a6e3a1"),
		firstHex(vars["base0C"], "#94e2d5"),
		firstHex(vars["base0D"], "#89b4fa"),
		firstHex(vars["base0E"], "#cba6f7"),
		firstHex(vars["base0F"], "#f2cdcd"))

	if err := writeFileAtomic(filepath.Join(themeDir, "aether-theme.css"), []byte(cssContent)); err != nil {
		warnings = append(warnings, fmt.Sprintf("jan theme css: %v", err))
	} else {
		applied = append(applied, "jan-theme-css")
	}

	return applied, warnings
}
