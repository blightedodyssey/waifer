// Package aetherdir manages Waifer's native Omarchy-style ecosystem directories
// under %LOCALAPPDATA%\Waifer on Windows. It provides canonical live theme
// exports, user drop-in templates, and post-apply hooks.
package aetherdir

import (
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"strings"
)

const (
	// waiferAppDir is the Windows runtime directory name.
	waiferAppDir = "Waifer"
	// legacyAppDir is the pre-rebrand Windows runtime directory, migrated on first run.
	legacyAppDir = "Aether"
	// nonWindowsAppDir keeps the historical Unix-style directory unchanged.
	nonWindowsAppDir = "aether"
)

// Root returns %LOCALAPPDATA%\Waifer on Windows, or ~/.local/share/aether on other platforms.
func Root() string {
	if runtime.GOOS == "windows" {
		if local := os.Getenv("LOCALAPPDATA"); local != "" {
			return filepath.Join(local, waiferAppDir)
		}
	}
	home, err := os.UserHomeDir()
	if err != nil {
		home = "."
	}
	return filepath.Join(home, ".local", "share", nonWindowsAppDir)
}

// CurrentDir returns %LOCALAPPDATA%\Waifer\current (the canonical live exports).
func CurrentDir() string {
	return filepath.Join(Root(), "current")
}

// TemplatesDir returns %LOCALAPPDATA%\Waifer\templates (user drop-in .tpl files).
func TemplatesDir() string {
	return filepath.Join(Root(), "templates")
}

// HooksDir returns %LOCALAPPDATA%\Waifer\hooks (post-apply scripts).
func HooksDir() string {
	return filepath.Join(Root(), "hooks")
}

// Ensure migrates any legacy %LOCALAPPDATA%\Aether tree and creates all Waifer
// ecosystem directories. Migration runs before MkdirAll so existing presets,
// blueprints and wallpapers land in the new root on first launch.
func Ensure() error {
	if err := MigrateFromLegacy(); err != nil {
		return fmt.Errorf("migrate legacy Aether data: %w", err)
	}
	for _, d := range []string{Root(), CurrentDir(), TemplatesDir(), HooksDir()} {
		if err := os.MkdirAll(d, 0755); err != nil {
			return fmt.Errorf("create Waifer dir %s: %w", d, err)
		}
	}
	return nil
}

// ExpandEnvVars replaces Windows-style %VAR% and Unix $VAR environment
// variable references in a path string.
func ExpandEnvVars(s string) string {
	if runtime.GOOS == "windows" {
		s = expandWindowsPercent(s)
	}
	// Also expand Unix $VAR style for cross-platform compatibility
	s = os.ExpandEnv(s)
	return s
}

// expandWindowsPercent replaces %VAR% style environment variables.
func expandWindowsPercent(s string) string {
	var result strings.Builder
	i := 0
	for i < len(s) {
		j := strings.Index(s[i:], "%")
		if j < 0 {
			result.WriteString(s[i:])
			break
		}
		result.WriteString(s[i : i+j])
		i += j + 1 // skip '%'
		k := strings.Index(s[i:], "%")
		if k < 0 {
			result.WriteByte('%')
			result.WriteString(s[i:])
			break
		}
		key := s[i : i+k]
		if val := os.Getenv(key); val != "" {
			result.WriteString(val)
		} else {
			result.WriteByte('%')
			result.WriteString(key)
			result.WriteByte('%')
		}
		i += k + 1 // skip closing '%'
	}
	return result.String()
}

// WriteColorsToml writes the canonical colors.toml to the current directory.
// It uses standard Omarchy/Base16 keys: background, foreground, cursor, accent, color0–color15.
func WriteColorsToml(vars map[string]string) error {
	if err := Ensure(); err != nil {
		return err
	}

	var b strings.Builder
	b.WriteString("# Waifer canonical theme colors (Omarchy/Base16 compatible)\n")
	b.WriteString("# Generated by Waifer. Do not edit manually — changes will be overwritten.\n\n")

	// Write keys in a stable order
	keys := []string{"background", "foreground", "cursor", "accent"}
	for _, k := range keys {
		if v := vars[k]; v != "" {
			fmt.Fprintf(&b, "%s = %q\n", k, v)
		}
	}

	b.WriteByte('\n')
	for i := 0; i < 16; i++ {
		key := fmt.Sprintf("color%d", i)
		if v := vars[key]; v != "" {
			fmt.Fprintf(&b, "%s = %q\n", key, v)
		}
	}

	path := filepath.Join(CurrentDir(), "colors.toml")
	if err := os.WriteFile(path, []byte(b.String()), 0644); err != nil {
		return fmt.Errorf("write colors.toml: %w", err)
	}
	return nil
}

// WriteThemeMeta writes theme.md (a simple markdown description) to the current directory.
func WriteThemeMeta(vars map[string]string, themeName string) error {
	if err := Ensure(); err != nil {
		return err
	}

	var b strings.Builder
	if themeName != "" {
		fmt.Fprintf(&b, "# %s\n\n", themeName)
	} else {
		b.WriteString("# Waifer Theme\n\n")
	}
	b.WriteString("Generated by Waifer.\n\n")
	b.WriteString("## Colors\n\n")
	for _, k := range []string{"background", "foreground", "cursor", "accent"} {
		if v := vars[k]; v != "" {
			fmt.Fprintf(&b, "- **%s**: `%s`\n", k, v)
		}
	}

	path := filepath.Join(CurrentDir(), "theme.md")
	if err := os.WriteFile(path, []byte(b.String()), 0644); err != nil {
		return fmt.Errorf("write theme.md: %w", err)
	}
	return nil
}

// WriteWallpaper copies the active wallpaper image into current\wallpaper (with preserved
// extension) and writes a wallpaper.path plain-text pointer.
func WriteWallpaper(sourcePath string) error {
	if err := Ensure(); err != nil {
		return err
	}
	if sourcePath == "" {
		// Remove existing wallpaper files (wallpaper.* + wallpaper.path)
		entries, _ := os.ReadDir(CurrentDir())
		for _, e := range entries {
			name := e.Name()
			if strings.HasPrefix(name, "wallpaper") {
				_ = os.Remove(filepath.Join(CurrentDir(), name))
			}
		}
		return nil
	}

	ext := strings.ToLower(filepath.Ext(sourcePath))
	if ext == "" {
		ext = ".jpg"
	}

	destPath := filepath.Join(CurrentDir(), "wallpaper"+ext)
	data, err := os.ReadFile(sourcePath)
	if err != nil {
		return fmt.Errorf("read wallpaper %s: %w", sourcePath, err)
	}
	if err := os.WriteFile(destPath, data, 0644); err != nil {
		return fmt.Errorf("write wallpaper: %w", err)
	}

	pathFile := filepath.Join(CurrentDir(), "wallpaper.path")
	if err := os.WriteFile(pathFile, []byte(sourcePath), 0644); err != nil {
		return fmt.Errorf("write wallpaper.path: %w", err)
	}
	return nil
}
