// findFirefoxProfile locates the active Firefox profile.
func findFirefoxProfile() (string, error) {
	appData := os.Getenv("APPDATA")
	if appData == "" {
		home, _ := os.UserHomeDir()
		appData = filepath.Join(home, "AppData", "Roaming")
	}
	root := filepath.Join(appData, "Mozilla", "Firefox")

	for _, name := range []string{"installs.ini", "profiles.ini"} {
		data, err := os.ReadFile(filepath.Join(root, name))
		if err != nil {
			continue
		}
		if profile := parseFirefoxProfileFromINI(data, root); profile != "" {
			if info, statErr := os.Stat(profile); statErr == nil && info.IsDir() {
				return profile, nil
			}
		}
	}

	// Fallback: exactly one profile dir
	profilesDir := filepath.Join(root, "Profiles")
	entries, err := os.ReadDir(profilesDir)
	if err == nil {
		var dirs []string
		for _, entry := range entries {
			if entry.IsDir() {
				dirs = append(dirs, filepath.Join(profilesDir, entry.Name()))
			}
		}
		if len(dirs) == 1 {
			return dirs[0], nil
		}
		for _, dir := range dirs {
			if strings.Contains(strings.ToLower(filepath.Base(dir)), ".default-release") {
				return dir, nil
			}
		}
	}
	return "", fmt.Errorf("no Firefox profile found")
}

func parseFirefoxProfileFromINI(data []byte, root string) string {
	type iniSection struct{ name string; values map[string]string }
	var sections []iniSection
	var current *iniSection

	scanner := bufio.NewScanner(bytes.NewReader(data))
	for scanner.Scan() {
		line := strings.TrimPrefix(scanner.Text(), "\ufeff")
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, ";") || strings.HasPrefix(line, "#") {
			continue
		}
		if strings.HasPrefix(line, "[") && strings.HasSuffix(line, "]") {
			sections = append(sections, iniSection{
				name:   strings.TrimSpace(line[1 : len(line)-1]),
				values: map[string]string{},
			})
			current = &sections[len(sections)-1]
			continue
		}
		if current == nil {
			continue
		}
		key, value, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		current.values[strings.ToLower(strings.TrimSpace(key))] = strings.TrimSpace(value)
	}

	var profiles []string
	for _, section := range sections {
		name := strings.ToLower(section.name)
		switch {
		case strings.HasPrefix(name, "install"):
			if path := strings.TrimSpace(section.values["default"]); path != "" {
				return resolveFirefoxProfilePath(root, path)
			}
		case strings.HasPrefix(name, "profile"):
			path := strings.TrimSpace(section.values["path"])
			if path == "" {
				continue
			}
			resolved := resolveFirefoxProfilePath(root, path)
			if section.values["default"] == "1" {
				return resolved
			}
			if resolved != "" {
				profiles = append(profiles, resolved)
			}
		}
	}
	if len(profiles) == 1 {
		return profiles[0]
	}
	return ""
}

func resolveFirefoxProfilePath(root, path string) string {
	path = strings.TrimSpace(path)
	if path == "" {
		return ""
	}
	if filepath.IsAbs(path) {
		return filepath.Clean(path)
	}
	return filepath.Join(root, filepath.FromSlash(path))
}

// writeFirefoxUserChrome writes both userChrome.css and userContent.css into
// the given Firefox profile, and ensures the preference to load them is enabled.
func writeFirefoxUserChrome(profileDir string, vars map[string]string) error {
	if strings.TrimSpace(profileDir) == "" {
		return fmt.Errorf("empty Firefox profile directory")
	}
	chromeDir := filepath.Join(profileDir, firefoxChromeDir)
	if err := os.MkdirAll(chromeDir, 0o755); err != nil {
		return fmt.Errorf("create firefox chrome dir: %w", err)
	}

	// userChrome.css
	chromePath := filepath.Join(chromeDir, firefoxCSSFile)
	if err := writeFileAtomic(chromePath, []byte(renderFirefoxChromeCSS(vars))); err != nil {
		return fmt.Errorf("write userChrome.css: %w", err)
	}

	// userContent.css
	contentPath := filepath.Join(chromeDir, firefoxContentFile)
	if err := writeFileAtomic(contentPath, []byte(renderFirefoxContentCSS(vars))); err != nil {
		return fmt.Errorf("write userContent.css: %w", err)
	}

	// user.js — append preference line without overwriting existing prefs
	if err := ensureFirefoxUserJSPref(profileDir); err != nil {
		return fmt.Errorf("update user.js: %w", err)
	}
	return nil
}

func ensureFirefoxUserJSPref(profileDir string) error {
	userJS := filepath.Join(profileDir, firefoxUserJSFile)
	prefLine := `user_pref("toolkit.legacyUserProfileCustomizations.stylesheets", true);`

	// If file exists, check if our line is already present
	data, err := os.ReadFile(userJS)
	if err != nil {
		if !os.IsNotExist(err) {
			return err
		}
		// File doesn't exist — create it
		content := firefoxUserJSTag + `. This preference was added by Aether.
` + prefLine + "\n"
		return writeFileAtomic(userJS, []byte(content))
	}

	// File exists — append if our pref is not present
	if strings.Contains(string(data), prefLine) {
		return nil // Already set
	}

	var b bytes.Buffer
	b.WriteString(string(data))
	if !bytes.HasSuffix(data, []byte("\n")) {
		b.WriteByte('\n')
	}
	b.WriteString("\n" + firefoxUserJSTag + "\n")
	b.WriteString(prefLine + "\n")
	return writeFileAtomic(userJS, b.Bytes())
}

