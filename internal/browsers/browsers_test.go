func TestDetectChromiumFamily(t *testing.T) {
	tempDir := t.TempDir()
	t.Setenv("LOCALAPPDATA", tempDir)
	
	// Create a Chrome User Data with Default profile
	chromeDir := filepath.Join(tempDir, "Google", "Chrome", "User Data")
	defaultProfile := filepath.Join(chromeDir, "Default")
	if err := os.MkdirAll(defaultProfile, 0o755); err != nil {
		t.Fatal(err)
	}

	defs := chromiumDefinitions()
	var chromeDef *chromiumDef
	for i := range defs {
		if defs[i].name == "chrome" {
			chromeDef = &defs[i]
			break
		}
	}
	if chromeDef == nil {
		t.Fatal("chrome definition not found")
	}

	info := detectChromiumFamily(*chromeDef)
	if !info.HasData {
		t.Fatal("expected chrome to be detected")
	}
	if len(info.Profiles) != 1 {
		t.Fatalf("expected 1 profile, got %d", len(info.Profiles))
	}
	if info.Profiles[0].Name != "Default" {
		t.Errorf("expected profile name Default, got %s", info.Profiles[0].Name)
	}
}

