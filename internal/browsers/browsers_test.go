func TestBlendHex(t *testing.T) {
	result := blendHex("#000000", "#ffffff", 0.5)
	// Integer truncation: 255*0.5 = 127.5 -> 127 = 0x7f
	if result != "#7F7F7F" && result != "#808080" {
		t.Errorf("blend middle = %s, want approximately #808080", result)
	}
}

