	t.Setenv("APPDATA", tempDir)

	// Setup Chrome
	chromeDir := filepath.Join(tempDir, "Google", "Chrome", "User Data", "Default")
	os.MkdirAll(chromeDir, 0o755)
	os.WriteFile(filepath.Join(chromeDir, "Preferences"), []byte(`{"browser":{}}`), 0o644)

	// Setup Firefox
	root := filepath.Join(tempDir, "Mozilla", "Firefox")
	profDir := filepath.Join(root, "Profiles", "test.default-release")
	os.MkdirAll(profDir, 0o755)
	os.WriteFile(filepath.Join(root, "profiles.ini"), []byte(`[Profile0]
Name=default
IsRelative=1
Path=Profiles/test.default-release
Default=1
`), 0o644)

	vars := map[string]string{
		"background":   "#1e1e2e",
		"foreground":   "#cdd6f4",
		"accent":       "#89b4fa",
		"dark_bg":      "#181825",
		"bright_black": "#45475a",
		"theme_type":   "dark",
	}

	applied, warnings := ApplyTheme(vars)
	if len(warnings) > 0 {
		t.Logf("warnings: %v", warnings)
	}
