func TestWriteChromiumExtension(t *testing.T) {
	tempDir := t.TempDir()
	t.Setenv("LOCALAPPDATA", tempDir)

	vars := map[string]string{
		"background":   "#1e1e2e",
		"foreground":   "#cdd6f4",
		"accent":       "#89b4fa",
		"dark_bg":      "#181825",
		"bright_black": "#45475a",
		"theme_type":   "dark",
	}

	if err := writeChromiumExtension(vars); err != nil {
		t.Fatalf("writeChromiumExtension: %v", err)
	}

	manifestPath := filepath.Join(ExtensionDir(), "manifest.json")
	data, err := os.ReadFile(manifestPath)
	if err != nil {
		t.Fatalf("read manifest: %v", err)
	}

	var manifest map[string]interface{}
	if err := json.Unmarshal(data, &manifest); err != nil {
		t.Fatalf("parse manifest: %v", err)
	}

	if manifest["manifest_version"] != float64(3) {
		t.Errorf("manifest_version = %v, want 3", manifest["manifest_version"])
	}
	if manifest["name"] != extensionName {
		t.Errorf("name = %v, want %q", manifest["name"], extensionName)
	}

	theme, ok := manifest["theme"].(map[string]interface{})
	if !ok {
		t.Fatal("theme key missing or wrong type")
	}

	colors, ok := theme["colors"].(map[string]interface{})
	if !ok {
		t.Fatal("colors key missing or wrong type")
	}

	frame, ok := colors["frame"].([]interface{})
	if !ok || len(frame) != 3 {
		t.Fatal("frame color not an [r,g,b] array")
	}
	if int(frame[0].(float64)) != 0x1e {
		t.Errorf("frame R = %v, want 30", frame[0])
	}
}

func TestPatchChromiumPreferences(t *testing.T) {
	profile := t.TempDir()
	prefsPath := filepath.Join(profile, "Preferences")

	// Write initial preferences
	initial := map[string]interface{}{
		"browser": map[string]interface{}{
			"theme": map[string]interface{}{
				"color_scheme": "system",
			},
		},
	}
	data, _ := json.Marshal(initial)
	os.WriteFile(prefsPath, data, 0o644)

	vars := map[string]string{
		"accent":     "#89b4fa",
		"theme_type": "dark",
	}

	if err := patchChromiumPreferences(profile, vars); err != nil {
		t.Fatalf("patchChromiumPreferences: %v", err)
	}

	patchedData, err := os.ReadFile(prefsPath)
	if err != nil {
		t.Fatalf("read patched preferences: %v", err)
	}

	var patched map[string]interface{}
	if err := json.Unmarshal(patchedData, &patched); err != nil {
		t.Fatalf("parse patched preferences: %v", err)
	}

	browser := patched["browser"].(map[string]interface{})
	theme := browser["theme"].(map[string]interface{})
	if theme["color_scheme2"] != "dark" {
		t.Errorf("color_scheme2 = %v, want dark", theme["color_scheme2"])
	}

	autogen := patched["autogenerated"].(map[string]interface{})
	autogenTheme := autogen["theme"].(map[string]interface{})
	colorVal, ok := autogenTheme["color"].(float64)
	if !ok {
		t.Fatal("autogenerated.theme.color not a number")
	}
	// #89b4fa -> 0xFF89B4FA
	expected := float64(0xFF89B4FA)
	if int64(colorVal) != int64(expected) {
		t.Errorf("autogenerated color = 0x%X, want 0x%X", int64(colorVal), int64(expected))
	}
}

