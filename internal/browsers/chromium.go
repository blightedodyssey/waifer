// safeHex ensures the hex string starts with # and defaults to black if empty.
func safeHex(v string) string {
	v = strings.TrimSpace(v)
	if v == "" {
		return "#000000"
	}
	if !strings.HasPrefix(v, "#") {
		v = "#" + v
	}
	return v
}

// hexToARGB converts a 6-char hex color to an ARGB integer (0xFFRRGGBB).
func hexToARGB(hex string) (int, error) {
	r, g, b, err := hexToRGB(hex)
	if err != nil {
		return 0, err
	}
	return (0xFF << 24) | (r << 16) | (g << 8) | b, nil
}

// setNestedMap sets a deeply nested value in map[string]interface{}.
func setNestedMap(root map[string]interface{}, path ...interface{}) {
	if len(path) < 2 {
		return
	}
	m := root
	for i := 0; i < len(path)-2; i++ {
		key, ok := path[i].(string)
		if !ok {
			return
		}
		next, ok := m[key].(map[string]interface{})
		if !ok || next == nil {
			next = make(map[string]interface{})
			m[key] = next
		}
		m = next
	}
	if finalKey, ok := path[len(path)-2].(string); ok {
		m[finalKey] = path[len(path)-1]
	}
}

// writeFileAtomic writes data to a temp file next to the target, then renames.
func writeFileAtomic(path string, data []byte) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	tmp := path + ".aether-tmp"
	if err := os.WriteFile(tmp, data, 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

// blendHex blends two hex colors by the given ratio (0-1).
func blendHex(a, b string, ratio float64) string {
	ra, ga, ba, err := hexToRGB(a)
	if err != nil {
		return a
	}
	rb, gb, bbl, err := hexToRGB(b)
	if err != nil {
		return a
	}
	ri := int(float64(ra)*(1-ratio) + float64(rb)*ratio)
	gi := int(float64(ga)*(1-ratio) + float64(gb)*ratio)
	bi := int(float64(ba)*(1-ratio) + float64(bbl)*ratio)
	return fmt.Sprintf("#%02X%02X%02X", ri, gi, bi)
}
