// writeChromiumExtension generates an unpacked Chrome MV3 theme extension
// mapping Aether palette tokens to Chromium theme colors.
func writeChromiumExtension(vars map[string]string) error {
	extDir := ExtensionDir()
	if err := os.MkdirAll(extDir, 0o755); err != nil {
		return fmt.Errorf("create extension dir: %w", err)
	}

	manifest := map[string]interface{}{
		"manifest_version": 3,
		"name":             extensionName,
		"version":          fmt.Sprintf("1.0.%d", time.Now().Unix()),
		"theme": map[string]interface{}{
			"colors": chromiumThemeColors(vars),
		},
	}

	data, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return fmt.Errorf("marshal manifest: %w", err)
	}
	data = append(data, '\n')

	if err := writeFileAtomic(filepath.Join(extDir, "manifest.json"), data); err != nil {
		return fmt.Errorf("write manifest: %w", err)
	}
	return nil
}

// chromiumThemeColors maps Aether palette variables to Chromium theme color keys.
// The full Base16 palette is exported so the extension can provide richer theming.
// The accent color is always derived from vars["accent"] (base0D / UI Accent) —
// it defaults to s.Palette[4] (blue) in buildColorRoles and is the same value
// used for every other Aether accent target.
func chromiumThemeColors(vars map[string]string) map[string][]int {
	bg := safeHex(vars["background"])
	fg := safeHex(vars["foreground"])
	accent := safeHex(vars["accent"])
	surface := safeHex(vars["dark_bg"])
	if surface == "#000000" || surface == bg {
		surface = blendHex(bg, "#000000", 0.15)
	}

	return map[string][]int{
		"frame":                  rgbArray(bg),
		"frame_inactive":         rgbArray(surface),
		"toolbar":                rgbArray(surface),
		"tab_text":               rgbArray(fg),
		"tab_background_text":    rgbArray(vars["bright_black"]),
		"bookmark_text":          rgbArray(fg),
		"ntp_background":         rgbArray(bg),
		"ntp_text":               rgbArray(fg),
		"omnibox_background":     rgbArray(blendHex(bg, "#000000", 0.08)),
		"omnibox_text":           rgbArray(fg),
		"button_background":      rgbArray(accent),
	}
}

// patchChromiumPreferences patches the "Preferences" JSON in a Chromium profile
// to set the active theme color and hint.  The write is atomic (write-temp-then-rename).
// If a sentinel lock file exists (indicating the browser is running), a warning
// is logged but the preferences are still patched. Preferences are JSON, not a
// live database, so the risk of corruption is low; the next Chrome start will
// pick up the new values.
func patchChromiumPreferences(profilePath string, vars map[string]string) error {
	prefsPath := filepath.Join(profilePath, "Preferences")

	data, err := os.ReadFile(prefsPath)
	if err != nil {
		if os.IsNotExist(err) {
			return nil // Fresh profile, nothing to patch
		}
		return fmt.Errorf("read Preferences: %w", err)
	}

	var prefs map[string]interface{}
	if err := json.Unmarshal(data, &prefs); err != nil {
		return fmt.Errorf("parse Preferences: %w", err)
	}

	// Set color_scheme2 ("dark", "light", "system")
	mode := "dark"
	if vars["theme_type"] == "light" || vars["mode"] == "light" {
		mode = "light"
	}

	setNestedMap(prefs, "browser", "theme", "color_scheme2", mode)

	// Set autogenerated.theme.color as an ARGB integer using the active accent
	// (base0D / UI Accent). This is the same value used for every other Aether
	// accent target — Windows DWM, Windhawk, Vencord, Obsidian, etc.
	accent := safeHex(vars["accent"])
	if accentARGB, err := hexToARGB(accent); err == nil {
		setNestedMap(prefs, "autogenerated", "theme", "color", accentARGB)
	}

	modified, err := json.MarshalIndent(prefs, "", "  ")
	if err != nil {
		return fmt.Errorf("encode Preferences: %w", err)
	}
	modified = append(modified, '\n')

	if err := writeFileAtomic(prefsPath, modified); err != nil {
		return fmt.Errorf("write Preferences: %w", err)
	}

	// Warn if Chrome is running — it will not see the change until restart, but
	// the DWM registry policy should have already applied live.
	lockPath := filepath.Join(profilePath, "LOCK")
	if _, err := os.Stat(lockPath); err == nil {
		return fmt.Errorf("browser is running (LOCK present); Preferences patched but will apply on next start")
	}
	return nil
}

