package browsers

import (
	"fmt"
	"os"
	"path/filepath"
	"runtime"
)

// The "Waifer WebUI Theme Sync" extension is an unpacked Chrome MV3 extension
// whose content script injects waifer-webui.css into gemini.google.com pages,
// so the Gemini WebUI window follows the active Waifer palette. Unlike the
// generated browser-theme extension, its directory is user-managed: Waifer
// only refreshes the stylesheet when the extension is actually loaded and
// never creates the directory on demand.

const (
	webUIExtensionName = "Waifer WebUI Theme Sync"
	webUICSSFile       = "waifer-webui.css"
)

// webUIExtensionDir returns the directory of the unpacked WebUI Theme Sync
// extension. A missing directory means the extension is not loaded in Chrome.
func webUIExtensionDir() string {
	if runtime.GOOS == "windows" {
		if local := os.Getenv("LOCALAPPDATA"); local != "" {
			return filepath.Join(local, "Waifer", "chrome-webui-ext")
		}
	}
	return filepath.Join(os.TempDir(), "waifer-chrome-webui-ext")
}

// RenderWebUICSS builds waifer-webui.css for the active palette. It is
// exported so the generated stylesheet can be inspected and tested without
// touching the real extension directory.
func RenderWebUICSS(vars map[string]string) string {
	bg := safeHex(vars["background"])
	fg := safeHex(vars["foreground"])
	accent := safeHex(vars["accent"])

	// The surface sits between panels as a near-opaque dark wash, mirroring
	// chromiumThemeColors: dark_bg when present, else a blend toward black.
	surface := safeHex(vars["dark_bg"])
	if surface == "#000000" || surface == bg {
		surface = blendHex(bg, "#000000", 0.15)
	}
	sr, sg, sb := 0, 0, 0
	if r, g, b, err := hexToRGB(surface); err == nil {
		sr, sg, sb = r, g, b
	}

	return fmt.Sprintf(`/* Generated by %s. Do not edit: Waifer overwrites this file. */

:root {
  --waifer-bg: %s;
  --waifer-surface: rgba(%d, %d, %d, 0.88);
  --waifer-fg: %s;
  --waifer-accent: %s;
}

body,
bard-sidenav-container,
.mat-sidenav-container,
chat-window,
.input-area-container {
  background-color: color-mix(in srgb, var(--waifer-bg) 22%%, #141218) !important;
}

bard-sidenav,
.sidenav-with-history-container {
  background-color: color-mix(in srgb, var(--waifer-bg) 14%%, #0f0d12) !important;
  border-right: 1px solid color-mix(in srgb, var(--waifer-accent) 45%%, transparent) !important;
}
`, webUIExtensionName, bg, sr, sg, sb, fg, accent)
}

// writeWebUIExtension regenerates waifer-webui.css inside the unpacked WebUI
// Theme Sync extension. When the extension directory is missing the extension
// is simply not loaded in Chrome, which is reported as an error so callers can
// log a non-fatal warning; the directory itself is never created.
func writeWebUIExtension(vars map[string]string) error {
	extDir := webUIExtensionDir()
	if info, err := os.Stat(extDir); err != nil || !info.IsDir() {
		return fmt.Errorf("%s extension not found at %s (load it in Chrome to sync the Gemini WebUI)", webUIExtensionName, extDir)
	}
	target := filepath.Join(extDir, webUICSSFile)
	if err := writeFileAtomic(target, []byte(RenderWebUICSS(vars))); err != nil {
		return fmt.Errorf("write %s: %w", webUICSSFile, err)
	}
	return nil
}
