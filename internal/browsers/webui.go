package browsers

import (
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"runtime"
)

// The "Waifer WebUI Theme Sync" extension is an unpacked Chrome MV3 extension
// for gemini.google.com. Waifer regenerates its three files on every Apply:
//
//   - manifest.json     content-script wiring plus web-accessible CSS
//   - waifer-webui.css  the active palette as CSS variables
//   - content.js        a watcher that hot-swaps the stylesheet into open
//                       tabs every 1.5s, so palette changes land without a
//                       page reload or an extension reload
//
// The directory is user-managed (the extension must be loaded in Chrome by
// hand): Waifer never creates it, and a missing directory is reported as an
// error so callers can log a non-fatal warning.

const (
	webUIExtensionName    = "Waifer WebUI Theme Sync"
	webUIExtensionVersion = "1.1.0"
	webUICSSFile          = "waifer-webui.css"
	webUIContentFile      = "content.js"
)

// webUIContentScript is the content script injected into gemini.google.com.
// It polls the generated stylesheet (cache-busted, no-store) and mirrors it
// into a <style id="waifer-webui-live"> element, so the regenerated CSS
// repaints every open Gemini tab within ~1.5s of an Apply.
const webUIContentScript = `// Generated by Waifer. Do not edit: Waifer overwrites this file.
(() => {
  const url = chrome.runtime.getURL("waifer-webui.css");
  const POLL_MS = 1500;
  let last = null;
  let style = null;

  const apply = (css) => {
    if (css === last) return;
    const root = document.head || document.documentElement;
    if (!root) return; // document_start: retry on the next tick
    last = css;
    if (!style || !style.isConnected) {
      style = document.createElement("style");
      style.id = "waifer-webui-live";
      root.append(style);
    }
    style.textContent = css;
  };

  const poll = async () => {
    try {
      const res = await fetch(url + "?t=" + Date.now(), { cache: "no-store" });
      if (res.ok) apply((await res.text()).trim());
    } catch {
      // Extension reloading or tab closing; retry on the next tick.
    }
  };

  poll();
  setInterval(poll, POLL_MS);
})();
`

type webUIContentScriptEntry struct {
	Matches []string `json:"matches"`
	JS      []string `json:"js"`
	CSS     []string `json:"css"`
	RunAt   string   `json:"run_at"`
}

type webUIAccessibleResource struct {
	Resources []string `json:"resources"`
	Matches   []string `json:"matches"`
}

type webUIManifest struct {
	ManifestVersion        int                       `json:"manifest_version"`
	Name                   string                    `json:"name"`
	Version                string                    `json:"version"`
	Description            string                    `json:"description"`
	ContentScripts         []webUIContentScriptEntry `json:"content_scripts"`
	WebAccessibleResources []webUIAccessibleResource `json:"web_accessible_resources"`
}

// webUIExtensionDir returns the directory of the unpacked WebUI Theme Sync
// extension. A missing directory means the extension is not loaded in Chrome.
func webUIExtensionDir() string {
	if runtime.GOOS == "windows" {
		if local := os.Getenv("LOCALAPPDATA"); local != "" {
			return filepath.Join(local, "Waifer", "chrome-webui-ext")
		}
	}
	return filepath.Join(os.TempDir(), "waifer-chrome-webui-ext")
}

// RenderWebUICSS builds waifer-webui.css for the active palette. It is
// exported so the generated stylesheet can be inspected and tested without
// touching the real extension directory.
func RenderWebUICSS(vars map[string]string) string {
	bg := safeHex(vars["background"])
	fg := safeHex(vars["foreground"])
	accent := safeHex(vars["accent"])

	// The surface sits between panels as a near-opaque dark wash, mirroring
	// chromiumThemeColors: dark_bg when present, else a blend toward black.
	surface := safeHex(vars["dark_bg"])
	if surface == "#000000" || surface == bg {
		surface = blendHex(bg, "#000000", 0.15)
	}
	sr, sg, sb := 0, 0, 0
	if r, g, b, err := hexToRGB(surface); err == nil {
		sr, sg, sb = r, g, b
	}

	return fmt.Sprintf(`/* Generated by %s. Do not edit: Waifer overwrites this file. */

:root {
  --waifer-bg: %s;
  --waifer-surface: rgba(%d, %d, %d, 0.88);
  --waifer-fg: %s;
  --waifer-accent: %s;
}

body,
bard-sidenav-container,
.mat-sidenav-container,
chat-window,
.input-area-container {
  background-color: color-mix(in srgb, var(--waifer-bg) 22%%, #141218) !important;
}

bard-sidenav,
.sidenav-with-history-container {
  background-color: color-mix(in srgb, var(--waifer-bg) 14%%, #0f0d12) !important;
  border-right: 1px solid color-mix(in srgb, var(--waifer-accent) 45%%, transparent) !important;
}
`, webUIExtensionName, bg, sr, sg, sb, fg, accent)
}

// RenderWebUIManifest builds the extension manifest. It is deterministic so
// re-applying a theme never churns manifest.json.
func RenderWebUIManifest() string {
	manifest := webUIManifest{
		ManifestVersion: 3,
		Name:            webUIExtensionName,
		Version:         webUIExtensionVersion,
		Description:     "Syncs Chrome WebUI windows with the active Waifer desktop palette.",
		ContentScripts: []webUIContentScriptEntry{{
			Matches: []string{"https://gemini.google.com/*"},
			JS:      []string{webUIContentFile},
			CSS:     []string{webUICSSFile},
			RunAt:   "document_start",
		}},
		WebAccessibleResources: []webUIAccessibleResource{{
			Resources: []string{webUICSSFile},
			Matches:   []string{"https://gemini.google.com/*"},
		}},
	}
	data, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil { // unreachable for a static struct
		return ""
	}
	return string(data) + "\n"
}

// writeWebUIExtension regenerates the WebUI Theme Sync extension files for the
// active palette. Every file is written atomically. When the extension
// directory is missing the extension is simply not loaded in Chrome, which is
// reported as an error so callers can log a non-fatal warning; the directory
// itself is never created.
func writeWebUIExtension(vars map[string]string) error {
	extDir := webUIExtensionDir()
	if info, err := os.Stat(extDir); err != nil || !info.IsDir() {
		return fmt.Errorf("%s extension not found at %s (load it in Chrome to sync the Gemini WebUI)", webUIExtensionName, extDir)
	}
	files := []struct {
		name string
		data []byte
	}{
		{"manifest.json", []byte(RenderWebUIManifest())},
		{webUIContentFile, []byte(webUIContentScript)},
		{webUICSSFile, []byte(RenderWebUICSS(vars))},
	}
	var errs []error
	for _, file := range files {
		if err := writeFileAtomic(filepath.Join(extDir, file.name), file.data); err != nil {
			errs = append(errs, fmt.Errorf("write %s: %w", file.name, err))
		}
	}
	return errors.Join(errs...)
}
