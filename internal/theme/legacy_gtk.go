package theme

import (
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"strings"

	"aether/internal/platform"
)

// aetherGTKMarker identifies stylesheets Aether wrote in older versions.
const aetherGTKMarker = "/* Generated by Aether"

// legacyGTKCandidates lists the stylesheet locations old Aether versions
// wrote directly. Modern releases only manage Omarchy themes, so leftovers
// are retired (removed) on startup.
func legacyGTKCandidates() []string {
	configRoot := platform.ConfigDir()
	if runtime.GOOS != "windows" {
		// Old versions wrote next to the GTK config, not Aether's own dir.
		configRoot = filepath.Join(platform.ExpandHome("~"), ".config")
	}
	return []string{
		filepath.Join(configRoot, "gtk-3.0", "gtk.css"),
		filepath.Join(configRoot, "gtk-4.0", "gtk.css"),
	}
}

// RetireLegacyGTKStylesheets removes Aether-generated GTK stylesheets left
// behind by older versions. Files without the Aether marker are untouched.
func RetireLegacyGTKStylesheets() error {
	for _, path := range legacyGTKCandidates() {
		if err := removeLegacyGTKStylesheet(path); err != nil {
			return err
		}
	}
	return nil
}

// removeLegacyGTKStylesheet deletes path when it is a verified legacy
// Aether stylesheet.
func removeLegacyGTKStylesheet(path string) error {
	ok, err := verifyLegacyGTKPath(path)
	if err != nil || !ok {
		return err
	}
	if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("remove legacy stylesheet %s: %w", path, err)
	}
	return nil
}

// verifyLegacyGTKPath reports whether path is an Aether-generated stylesheet.
func verifyLegacyGTKPath(path string) (bool, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return false, nil
		}
		return false, fmt.Errorf("inspect legacy stylesheet %s: %w", path, err)
	}
	return strings.Contains(string(data), aetherGTKMarker), nil
}
