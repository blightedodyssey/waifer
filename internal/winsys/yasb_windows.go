//go:build windows

package winsys

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// ApplyYasbTheme writes Aether palette CSS custom properties to
// %USERPROFILE%\.config\yasb\aether-colors.css and ensures an @import is
// present at the top of styles.css so YASB picks up the live colors.
func ApplyYasbTheme(vars map[string]string) error {
	home, err := os.UserHomeDir()
	if err != nil {
		return fmt.Errorf("resolve user home: %w", err)
	}
	yasbDir := filepath.Join(home, ".config", "yasb")

	// Build CSS custom properties from the active palette.
	css := buildYasbCSS(vars)

	// Write aether-colors.css
	colorsPath := filepath.Join(yasbDir, "aether-colors.css")
	if err := os.MkdirAll(yasbDir, 0o755); err != nil {
		return fmt.Errorf("create yasb config directory: %w", err)
	}
	if err := os.WriteFile(colorsPath, []byte(css), 0o644); err != nil {
		return fmt.Errorf("write aether-colors.css: %w", err)
	}

	// Ensure styles.css has an @import for aether-colors.css at the top.
	stylesPath := filepath.Join(yasbDir, "styles.css")
	if data, err := os.ReadFile(stylesPath); err == nil {
		importLine := "@import \"aether-colors.css\";"
		content := string(data)
		if !strings.Contains(content, importLine) {
			updated := importLine + "\n" + content
			if err := os.WriteFile(stylesPath, []byte(updated), 0o644); err != nil {
				return fmt.Errorf("prepend @import to styles.css: %w", err)
			}
		}
	}
	// If styles.css does not exist, write it with just the @import.
	if _, err := os.Stat(stylesPath); os.IsNotExist(err) {
		importOnly := "@import \"aether-colors.css\";\n"
		if err := os.WriteFile(stylesPath, []byte(importOnly), 0o644); err != nil {
			return fmt.Errorf("write styles.css: %w", err)
		}
	}

	return nil
}

// buildYasbCSS generates CSS custom properties for YASB from the palette vars.
func buildYasbCSS(vars map[string]string) string {
	bg := normalizeHex(vars["background"])
	fg := normalizeHex(vars["foreground"])
	accent := normalizeHex(vars["accent"])
	if bg == "" {
		bg = "#141114"
	}
	if fg == "" {
		fg = "#e6e1eb"
	}
	if accent == "" {
		accent = "#cba6f7"
	}

	var sb strings.Builder
	sb.WriteString("/* Generated by Aether — YASB Theme Colors */\n")
	sb.WriteString(":root {\n")

	write := func(key, value string) {
		if value != "" {
			sb.WriteString(fmt.Sprintf("  --%s: %s;\n", key, value))
		}
	}

	write("base00", normalizeHex(vars["black"]))
	write("base01", normalizeHex(vars["bright_black"]))
	write("base02", normalizeHex(vars["dark_bg"]))
	write("base03", normalizeHex(vars["darker_bg"]))
	write("base04", normalizeHex(vars["lighter_bg"]))
	write("base05", fg)
	write("base06", normalizeHex(vars["dark_fg"]))
	write("base07", normalizeHex(vars["light_fg"]))
	write("base08", normalizeHex(vars["red"]))
	write("base09", normalizeHex(vars["green"]))
	write("base0A", normalizeHex(vars["yellow"]))
	write("base0B", normalizeHex(vars["blue"]))
	write("base0C", normalizeHex(vars["magenta"]))
	write("base0D", accent)
	write("base0E", normalizeHex(vars["cyan"]))
	write("base0F", normalizeHex(vars["white"]))
	write("bg", bg)
	write("fg", fg)
	write("accent", accent)

	sb.WriteString("}\n")
	return sb.String()
}
