//go:build windows

package winsys

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const obsidianSnippetName = "aether"

type obsidianConfig struct {
	Vaults map[string]struct {
		Path string `json:"path"`
	} `json:"vaults"`
}

// discoverObsidianVaults parses %APPDATA%\obsidian\obsidian.json and returns
// existing vault directories.
func discoverObsidianVaults(appData string) ([]string, error) {
	if strings.TrimSpace(appData) == "" {
		return nil, fmt.Errorf("APPDATA is not set")
	}
	cfgPath := filepath.Join(appData, "obsidian", "obsidian.json")
	data, err := os.ReadFile(cfgPath)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, fmt.Errorf("read obsidian.json: %w", err)
	}

	var cfg obsidianConfig
	if err := json.Unmarshal(data, &cfg); err != nil {
		return nil, fmt.Errorf("parse obsidian.json: %w", err)
	}

	var vaults []string
	seen := make(map[string]bool, len(cfg.Vaults))
	for _, v := range cfg.Vaults {
		p := strings.TrimSpace(v.Path)
		if p == "" {
			continue
		}
		clean := filepath.Clean(p)
		key := strings.ToLower(clean)
		if seen[key] {
			continue
		}
		if info, err := os.Stat(clean); err == nil && info.IsDir() {
			seen[key] = true
			vaults = append(vaults, clean)
		}
	}
	return vaults, nil
}

// ApplyObsidian writes <vault>\.obsidian\snippets\aether.css and enables the
// "aether" CSS snippet in <vault>\.obsidian\appearance.json for every
// discovered Obsidian vault.
func ApplyObsidian(vars map[string]string, themeDir string, lightMode bool) error {
	vaults, err := discoverObsidianVaults(appDataDir())
	if err != nil {
		return err
	}
	if len(vaults) == 0 {
		return fmt.Errorf("no Obsidian vaults found in %%APPDATA%%\\obsidian\\obsidian.json")
	}

	css := renderObsidianCSS(themeDir, vars)
	var firstErr error
	appliedCount := 0
	for _, vault := range vaults {
		if err := applyObsidianVault(vault, css, lightMode); err != nil {
			if firstErr == nil {
				firstErr = fmt.Errorf("vault %s: %w", filepath.Base(vault), err)
			}
			continue
		}
		appliedCount++
	}
	if appliedCount == 0 && firstErr != nil {
		return firstErr
	}
	return nil
}

func applyObsidianVault(vaultPath string, css []byte, lightMode bool) error {
	obsidianDir := filepath.Join(vaultPath, ".obsidian")
	snippetsDir := filepath.Join(obsidianDir, "snippets")
	if err := os.MkdirAll(snippetsDir, 0o755); err != nil {
		return fmt.Errorf("create snippets directory: %w", err)
	}

	snippetPath := filepath.Join(snippetsDir, obsidianSnippetName+".css")
	if err := writeFileAtomic(snippetPath, css); err != nil {
		return fmt.Errorf("write aether.css snippet: %w", err)
	}

	appearancePath := filepath.Join(obsidianDir, "appearance.json")
	root := map[string]any{}
	if raw, err := os.ReadFile(appearancePath); err == nil {
		if len(strings.TrimSpace(string(raw))) > 0 {
			parsed, parseErr := parseJSONC(raw)
			if parseErr != nil {
				return fmt.Errorf("parse appearance.json: %w", parseErr)
			}
			root = parsed
		}
		backup := appearancePath + ".aether-backup"
		if _, bErr := os.Stat(backup); os.IsNotExist(bErr) {
			_ = copyFile(appearancePath, backup)
		}
	} else if !os.IsNotExist(err) {
		return fmt.Errorf("read appearance.json: %w", err)
	}

	var snippets []string
	if existing, ok := root["enabledCssSnippets"].([]any); ok {
		for _, item := range existing {
			if s, ok := item.(string); ok && s != "" {
				snippets = append(snippets, s)
			}
		}
	}
	hasAether := false
	for _, s := range snippets {
		if strings.EqualFold(s, obsidianSnippetName) {
			hasAether = true
			break
		}
	}
	if !hasAether {
		snippets = append(snippets, obsidianSnippetName)
	}
	root["enabledCssSnippets"] = snippets
	if lightMode {
		root["theme"] = "moonstone"
	} else {
		root["theme"] = "obsidian"
	}

	encoded, err := json.MarshalIndent(root, "", "  ")
	if err != nil {
		return fmt.Errorf("encode appearance.json: %w", err)
	}
	encoded = append(encoded, '\n')
	if err := writeFileAtomic(appearancePath, encoded); err != nil {
		return fmt.Errorf("write appearance.json: %w", err)
	}
	return nil
}

func renderObsidianCSS(themeDir string, vars map[string]string) []byte {
	if themeDir != "" {
		if data, err := os.ReadFile(filepath.Join(themeDir, "obsidian.css")); err == nil && len(data) > 0 {
			return data
		}
	}
	c := func(key, fallback string) string {
		if v := normalizeHex(vars[key]); v != "" {
			return v
		}
		return fallback
	}
	bg := c("background", "#141114")
	lighterBg := c("lighter_bg", "#1e1a20")
	darkBg := c("dark_bg", "#0e0c0f")
	darkerBg := c("darker_bg", "#09080a")
	fg := c("foreground", "#e6e1eb")
	muted := c("muted", "#7f7888")
	brightBlack := c("bright_black", "#45404c")
	accent := c("accent", "#89b4fa")
	selBg := c("selection_background", accent)

	content := fmt.Sprintf(`/* Generated by Aether — Obsidian CSS Snippet */

body.theme-dark,
body.theme-light {
  --background-primary: %s;
  --background-primary-alt: %s;
  --background-secondary: %s;
  --background-secondary-alt: %s;
  --background-modifier-border: %s;
  --background-modifier-hover: %s;
  --background-modifier-active-hover: %s;
  --background-modifier-error: %s;
  --background-modifier-success: %s;

  --text-normal: %s;
  --text-muted: %s;
  --text-faint: %s;
  --text-accent: %s;
  --text-accent-hover: %s;
  --text-on-accent: %s;
  --text-selection: %s;
  --text-error: %s;
  --text-warning: %s;
  --text-success: %s;

  --interactive-normal: %s;
  --interactive-hover: %s;
  --interactive-accent: %s;
  --interactive-accent-hover: %s;
}
`,
		bg, lighterBg, darkBg, darkerBg, brightBlack,
		rgba(accent, 0.15), rgba(accent, 0.25),
		c("red", "#f38ba8"), c("green", "#a6e3a1"),
		fg, muted, brightBlack, accent, c("bright_blue", "#89b4fa"), bg,
		rgba(selBg, 0.35),
		c("red", "#f38ba8"), c("yellow", "#f9e2af"), c("green", "#a6e3a1"),
		lighterBg, brightBlack, accent, c("bright_blue", "#89b4fa"),
	)
	return []byte(content)
}

func restoreObsidianTheme() error {
	vaults, err := discoverObsidianVaults(appDataDir())
	if err != nil {
		return nil
	}
	for _, vault := range vaults {
		snippetPath := filepath.Join(vault, ".obsidian", "snippets", obsidianSnippetName+".css")
		_ = os.Remove(snippetPath)
		appearancePath := filepath.Join(vault, ".obsidian", "appearance.json")
		_ = restoreBackup(appearancePath)
	}
	return nil
}
