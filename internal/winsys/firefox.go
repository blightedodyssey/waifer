func firstColor(value, fallback string) string {
	if normalized := normalizeHex(value); normalized != "" {
		return normalized
	}
	return fallback
}

func rgba(hex string, alpha float64) string {
	r, g, b, err := parseHexColor(hex)
	if err != nil {
		return "rgba(255, 255, 255, 0.2)"
	}
	return fmt.Sprintf("rgba(%d, %d, %d, %.2f)", r, g, b, alpha)
}

// writeFirefoxUserChrome writes the generated stylesheet into a profile,
// backing up an existing userChrome.css once. It also creates user.js when the
// profile has none, because Firefox ignores userChrome.css until
// toolkit.legacyUserProfileCustomizations.stylesheets is enabled.
func writeFirefoxUserChrome(profileDir string, vars map[string]string) error {
	if strings.TrimSpace(profileDir) == "" {
		return fmt.Errorf("empty Firefox profile directory")
	}
	chromeDir := filepath.Join(profileDir, firefoxChromeDir)
	if err := os.MkdirAll(chromeDir, 0o755); err != nil {
		return fmt.Errorf("create Firefox chrome directory: %w", err)
	}

	target := filepath.Join(chromeDir, firefoxCSSFile)
	backup := target + firefoxBackupExt
	if _, err := os.Stat(backup); os.IsNotExist(err) {
		if _, statErr := os.Stat(target); statErr == nil {
			if err := copyFile(target, backup); err != nil {
				return fmt.Errorf("back up Firefox userChrome.css: %w", err)
			}
		}
	}
	if err := writeFileAtomic(target, []byte(RenderFirefoxCSS(vars))); err != nil {
		return fmt.Errorf("write Firefox userChrome.css: %w", err)
	}

	userJS := filepath.Join(profileDir, firefoxUserJSFile)
	if _, err := os.Stat(userJS); os.IsNotExist(err) {
		content := firefoxUserJSTag + ". Generated values are safe to remove.\n" + firefoxPrefLine + "\n"
		if err := writeFileAtomic(userJS, []byte(content)); err != nil {
			return fmt.Errorf("enable Firefox userChrome.css: %w", err)
		}
	}
	return nil
}

// restoreFirefoxUserChrome returns the profile to its pre-Aether state.
func restoreFirefoxUserChrome(profileDir string) error {
	if strings.TrimSpace(profileDir) == "" {
		return nil
	}
	target := filepath.Join(profileDir, firefoxChromeDir, firefoxCSSFile)
	backup := target + firefoxBackupExt

	if _, err := os.Stat(backup); err == nil {
		if err := copyFile(backup, target); err != nil {
			return fmt.Errorf("restore Firefox userChrome.css: %w", err)
		}
		if err := os.Remove(backup); err != nil {
			return fmt.Errorf("remove Firefox backup: %w", err)
		}
	} else if data, err := os.ReadFile(target); err == nil && bytes.Contains(data, []byte(firefoxCSSMarker)) {
		if err := os.Remove(target); err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("remove Firefox userChrome.css: %w", err)
		}
	}

	userJS := filepath.Join(profileDir, firefoxUserJSFile)
	if data, err := os.ReadFile(userJS); err == nil && bytes.Contains(data, []byte(firefoxUserJSTag)) {
		if err := os.Remove(userJS); err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("remove Firefox user.js: %w", err)
		}
	}
	return nil
}
