type iniSection struct {
	name   string
	values map[string]string
}

// findFirefoxProfile locates the active Firefox profile below %APPDATA%. It
// prefers installs.ini (which Firefox updates for the running installation)
// and then profiles.ini's Default=1 entry.
func findFirefoxProfile(appData string) (string, error) {
	if strings.TrimSpace(appData) == "" {
		return "", fmt.Errorf("APPDATA is not set")
	}
	root := filepath.Join(appData, "Mozilla", "Firefox")

	for _, name := range []string{"installs.ini", "profiles.ini"} {
		data, err := os.ReadFile(filepath.Join(root, name))
		if err != nil {
			continue
		}
		if profile := profileFromINI(data, root); profile != "" {
			if info, statErr := os.Stat(profile); statErr == nil && info.IsDir() {
				return profile, nil
			}
		}
	}

	// A profile can exist without being marked default (for example after an
	// interrupted first run). Use it only when there is no ambiguity.
	profilesDir := filepath.Join(root, "Profiles")
	entries, err := os.ReadDir(profilesDir)
	if err == nil {
		var dirs []string
		for _, entry := range entries {
			if entry.IsDir() {
				dirs = append(dirs, filepath.Join(profilesDir, entry.Name()))
			}
		}
		if len(dirs) == 1 {
			return dirs[0], nil
		}
		for _, dir := range dirs {
			if strings.Contains(strings.ToLower(filepath.Base(dir)), ".default-release") {
				return dir, nil
			}
		}
	}

	return "", fmt.Errorf("Firefox profile not found under %s (start Firefox once, then re-apply)", root)
}

func profileFromINI(data []byte, root string) string {
	sections := parseINI(data)
	var profiles []string
	for _, section := range sections {
		name := strings.ToLower(section.name)
		switch {
		case strings.HasPrefix(name, "install"):
			// [Install...] Default=Profiles/xxxx.default-release
			if path := strings.TrimSpace(section.values["default"]); path != "" {
				if resolved := resolveProfilePath(root, path); resolved != "" {
					return resolved
				}
			}
		case strings.HasPrefix(name, "profile"):
			path := strings.TrimSpace(section.values["path"])
			if path == "" {
				continue
			}
			resolved := resolveProfilePath(root, path)
			if section.values["default"] == "1" {
				return resolved
			}
			if resolved != "" {
				profiles = append(profiles, resolved)
			}
		}
	}
	if len(profiles) == 1 {
		return profiles[0]
	}
	return ""
}

func parseINI(data []byte) []iniSection {
	var sections []iniSection
	var current *iniSection

	scanner := bufio.NewScanner(bytes.NewReader(data))
	for scanner.Scan() {
		line := strings.TrimPrefix(scanner.Text(), "\ufeff")
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, ";") || strings.HasPrefix(line, "#") {
			continue
		}
		if strings.HasPrefix(line, "[") && strings.HasSuffix(line, "]") {
			sections = append(sections, iniSection{
				name:   strings.TrimSpace(line[1 : len(line)-1]),
				values: map[string]string{},
			})
			current = &sections[len(sections)-1]
			continue
		}
		if current == nil {
			continue
		}
		key, value, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		current.values[strings.ToLower(strings.TrimSpace(key))] = strings.TrimSpace(value)
	}
	return sections
}

func resolveProfilePath(root, path string) string {
	path = strings.TrimSpace(path)
	if path == "" {
		return ""
	}
	if filepath.IsAbs(path) {
		return filepath.Clean(path)
	}
	return filepath.Join(root, filepath.FromSlash(path))
}

