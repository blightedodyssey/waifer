package winsys

import (
	"fmt"
	"strings"
)

func neovimColorscheme(vars map[string]string) string {
	c := func(name string) string {
		v := vars[name]
		if v == "" {
			return "#000000"
		}
		return v
	}
	background := "dark"
	if vars["mode"] == "light" {
		background = "light"
	}

	var b strings.Builder
	b.WriteString("-- Generated by Aether. Re-apply the theme instead of editing.\n")
	b.WriteString("vim.cmd(\"highlight clear\")\n")
	b.WriteString("if vim.fn.exists(\"syntax_on\") == 1 then vim.cmd(\"syntax reset\") end\n")
	b.WriteString("vim.o.background = \"" + background + "\"\n")
	b.WriteString("vim.g.colors_name = \"aether\"\n\n")
	b.WriteString("local set = vim.api.nvim_set_hl\n")

	groups := []struct {
		group  string
		fg, bg string
		bold   bool
	}{
		{"Normal", c("foreground"), c("background"), false},
		{"NormalFloat", c("foreground"), c("lighter_bg"), false},
		{"CursorLine", "", c("lighter_bg"), false},
		{"CursorLineNr", c("accent"), "", true},
		{"LineNr", c("muted"), "", false},
		{"Comment", c("muted"), "", false},
		{"Constant", c("cyan"), "", false},
		{"String", c("green"), "", false},
		{"Identifier", c("cyan"), "", false},
		{"Function", c("blue"), "", false},
		{"Statement", c("magenta"), "", false},
		{"Keyword", c("magenta"), "", false},
		{"Operator", c("bright_fg"), "", false},
		{"Type", c("yellow"), "", false},
		{"Special", c("orange"), "", false},
		{"PreProc", c("magenta"), "", false},
		{"Error", c("bright_red"), "", true},
		{"Todo", c("accent"), "", true},
		{"Visual", "", c("selection"), false},
		{"Search", c("background"), c("accent"), false},
		{"Pmenu", c("foreground"), c("lighter_bg"), false},
		{"PmenuSel", c("background"), c("accent"), true},
		{"StatusLine", c("foreground"), c("lighter_bg"), false},
		{"StatusLineNC", c("muted"), c("background"), false},
		{"VertSplit", c("lighter_bg"), "", false},
		{"DiffAdd", c("green"), "", false},
		{"DiffChange", c("yellow"), "", false},
		{"DiffDelete", c("red"), "", false},
	}
	for _, g := range groups {
		attrs := make([]string, 0, 3)
		if g.fg != "" {
			attrs = append(attrs, fmt.Sprintf("fg = %q", g.fg))
		}
		if g.bg != "" {
			attrs = append(attrs, fmt.Sprintf("bg = %q", g.bg))
		}
		if g.bold {
			attrs = append(attrs, "bold = true")
		}
		fmt.Fprintf(&b, "set(0, %q, { %s })\n", g.group, strings.Join(attrs, ", "))
	}

	order := []string{
		"black", "red", "green", "yellow", "blue", "magenta", "cyan", "white",
		"bright_black", "bright_red", "bright_green", "bright_yellow",
		"bright_blue", "bright_magenta", "bright_cyan", "bright_white",
	}
	b.WriteString("\n")
	for i, name := range order {
		fmt.Fprintf(&b, "vim.g.terminal_color_%d = %q\n", i, c(name))
	}
	return b.String()
}
